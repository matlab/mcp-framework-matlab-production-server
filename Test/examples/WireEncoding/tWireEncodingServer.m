            gradient_B = struct( ...
                'uri', 'mcp://wire-encoding/data/gradient-frame-B', ...
                'contents', fullfile(df, "gradient_frame_B.csv"), ...
                'name', 'gradient_frame_B', ...
                'title', 'Thermal Gradient Frame B', ...
                'description', '12x10 int16 edge detection (100 ms later).', ...
                'mimeType', 'text/csv');

            resources = [audio_crossover, emi_filter, vibration, temperature, ...
                         pressure, rangefinder, thermal_A, thermal_B, ...
                         gradient_A, gradient_B];
        end

    end
end
